export function getActivityById(id: string): Activity | undefined {
  return activities.find(activity => activity.id === id);
}

export function getFeaturedActivities(): Activity[] {
  return activities.filter(activity => activity.isFeatured);
}

export function getUpcomingActivities(limit?: number): Activity[] {
  const sorted = [...activities].sort((a, b) => a.date.getTime() - b.date.getTime());
  return limit ? sorted.slice(0, limit) : sorted;
}
